export const translations = Object.fromEntries(
  Object.entries(rows).map(([lang, values]) => [
    lang,
    Object.fromEntries(keys.map((key, i) => [key, values[i]])),
  ])
) as Record<string, Record<string, string>>;
export function translate(language: Language, text: string) {
  return translations[language]?.[text] || text;
}
const Context = createContext({
  language: 'en' as Language,
  setLanguage: (_: Language) => {},
  t: (text: string) => text,
});
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('salem-language');
      return LANGUAGES.some((l) => l.code === saved) ? (saved as Language) : 'en';
    } catch {
      return 'en';
    }
  });
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    try {
      localStorage.setItem('salem-language', language);
    } catch {
      /* Session-only preference. */
    }
  }, [language]);
  return (
    <Context.Provider value={{ language, setLanguage, t: (text) => translate(language, text) }}>
      {children}
    </Context.Provider>
  );
}
export const useLanguage = () => useContext(Context);
